def format_bib(prefix: str | None, sequence: int) -> str:
    """Match EventDistance.FormatBib: prefix + D4."""
    num = f"{sequence:04d}"
    p = (prefix or "").strip()
    return f"{p}{num}" if p else num


def sql_str(v) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)) and not isinstance(v, bool):
        return str(v)
    s = str(v).replace("'", "''")
    return f"'{s}'"


def sql_json(obj) -> str:
    raw = json.dumps(obj, ensure_ascii=False, separators=(",", ":"))
    # dollar-quote to keep unicode + escapes intact
    tag = "j"
    while f"${tag}$" in raw:
        tag += "x"
    return f"${tag}${raw}${tag}$::jsonb"


def sql_ts(v: str | None) -> str:
    if not v:
        return "NULL"
    return f"TIMESTAMPTZ '{v}'"


def sql_date(v: str | None) -> str:
    if not v:
        return "NULL"
    return f"DATE '{v[:10]}'"


def sql_time(v: str | None) -> str:
    if not v:
        return "NULL"
    # "06:15:00" or "06:15:00.xxx"
    t = v[:8] if len(v) >= 8 else v
    return f"TIME '{t}'"


def load(name: str):
    p = SNAP / name
    text = p.read_text(encoding="utf-8").strip()
    if not text or text == "null":
        return None
    return json.loads(text)


