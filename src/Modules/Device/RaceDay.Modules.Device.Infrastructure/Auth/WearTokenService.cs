using System.IdentityModel.Tokens.Jwt;
using System.Security.Claims;
using System.Text;
using Microsoft.Extensions.Configuration;
using Microsoft.IdentityModel.Tokens;
using RaceDay.Modules.Device.Application.Abstractions;
using RaceDay.Modules.Device.Domain.Auth;

namespace RaceDay.Modules.Device.Infrastructure.Auth;

public sealed class WearTokenService(IConfiguration configuration) : IWearTokenService
{
    public const string ScopeSosCreate = "sos:create";

    public WearTokenPair Issue(LinkedDevice device)
    {
        var issuer = configuration["Jwt:Issuer"] ?? "raceday";
        var audience = configuration["Jwt:Audience"] ?? "raceday-clients";
        var signingKey = configuration["Jwt:SigningKey"]
            ?? throw new InvalidOperationException("Jwt:SigningKey is missing.");

        var expiresIn = 3600;
        var claims = new List<Claim>
        {
            new(JwtRegisteredClaimNames.Sub, device.RunnerUserId.ToString()),
            new(ClaimTypes.NameIdentifier, device.RunnerUserId.ToString()),
            new("device_id", device.Id.ToString()),
            new("scope", ScopeSosCreate),
            new("token_use", "wear")
        };

        var key = new SymmetricSecurityKey(Encoding.UTF8.GetBytes(signingKey));
        var credentials = new SigningCredentials(key, SecurityAlgorithms.HmacSha256);
        var token = new JwtSecurityToken(
            issuer: issuer,
            audience: audience,
            claims: claims,
            expires: DateTime.UtcNow.AddSeconds(expiresIn),
            signingCredentials: credentials);

        var access = new JwtSecurityTokenHandler().WriteToken(token);
        // Refresh plaintext is generated by caller; placeholder unused when caller supplies refresh.
        return new WearTokenPair(access, string.Empty, expiresIn, ScopeSosCreate);
    }
}
